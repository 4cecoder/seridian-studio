#!/usr/bin/env python3
"""Regenerates fns.zig: one alias per `pub fn` of the window's section files, so any section calls any other
as `fns.name(...)` (the C file had one flat namespace). Run from this directory after adding a function:
    python3 gen_fns.py > fns.zig
"""
import re
import sys
from pathlib import Path

SECTIONS = [
    "widgets.zig",
    "mixer_tracks.zig",
    "project.zig",
    "settings_transport.zig",
    "piano.zig",
    "actions_popout.zig",
    "mixer.zig",
    "control.zig",
    "preflight_panel.zig",
    "idle_inhibit_ui.zig",
]

here = Path(__file__).resolve().parent
out = [
    "//! GENERATED by gen_fns.py: do not edit. Every `pub fn` of the window's section files, so a section calls",
    "//! another as `fns.name(...)`, like the single namespace of the C file they were translated from.",
    "",
]
seen = {}
for name in SECTIONS:
    path = here / name
    if not path.exists():
        continue
    alias = name[:-4]
    out.append(f'const {alias} = @import("{name}");')
out.append("")
for name in SECTIONS:
    path = here / name
    if not path.exists():
        continue
    alias = name[:-4]
    for match in re.finditer(r"^pub (?:export )?fn ([A-Za-z_][A-Za-z0-9_]*)\(", path.read_text(), re.M):
        fn = match.group(1)
        if fn in seen:
            sys.exit(f"{fn} is defined in both {seen[fn]} and {name}")
        seen[fn] = name
        out.append(f"pub const {fn} = {alias}.{fn};")
print("\n".join(out))
